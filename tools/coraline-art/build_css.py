#!/usr/bin/env python3
"""Builds src/coraline.css from src/coraline.src.css.   Run from the project root:   python3 tools/coraline-art/build_css.py

Shorthands used in the source file
  @H      html[data-secret-theme="on"][data-secret-preset="coraline"]                    (only while CORALINE is unlocked)
  @T      @H[data-yn-theme]:root                                                          (as specific as the Theme Studio's own rules)
  @U      @H[data-yn-theme][data-yn-theme]:root                                           (one notch stronger: beats the Studio's colour-token surface rules)
  @CARDS  the list of "paper card" selectors, meant for use inside :is( ... )
  @EDGE_A / _B / _C / _PANEL / _BANNER / _TAG   hand-torn paper edges, generated below as clip-path polygons (deterministic: same output every run)
"""
import random, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC, OUT = ROOT / 'src' / 'coraline.src.css', ROOT / 'src' / 'coraline.css'

def torn(seed, nx, ny, ax, ay, step=.55):
    """Clockwise polygon(...) of a rectangle whose four edges are nibbled inwards by a bounded random walk (percent units)."""
    r = random.Random(seed)
    def walk(n, amp):
        v, out = r.uniform(0, amp), []
        for _ in range(n):
            v = min(amp, max(0, v + r.uniform(-step, step) * amp))
            if r.random() < .12: v = min(amp, v + amp * .6)      # an occasional deeper nick
            out.append(v)
        return out
    pts = []
    for i, d in enumerate(walk(nx, ay)): pts.append((100 * i / (nx - 1), d))                 # top, left -> right
    for i, d in enumerate(walk(ny, ax)): pts.append((100 - d, 100 * i / (ny - 1)))           # right, top -> bottom
    for i, d in enumerate(walk(nx, ay)): pts.append((100 - 100 * i / (nx - 1), 100 - d))     # bottom, right -> left
    for i, d in enumerate(walk(ny, ax)): pts.append((d, 100 - 100 * i / (ny - 1)))           # left, bottom -> top
    fmt = lambda v: ('%.1f' % v).rstrip('0').rstrip('.') + '%'
    return 'polygon(' + ', '.join(f'{fmt(x)} {fmt(y)}' for x, y in pts) + ')'

EDGES = {
    'EDGE_A': torn(11, 13, 17, 1.9, 1.2), 'EDGE_B': torn(23, 13, 17, 1.9, 1.2), 'EDGE_C': torn(37, 13, 17, 1.9, 1.2),
    'EDGE_PANEL': torn(5, 20, 12, 1.0, 1.7), 'EDGE_BANNER': torn(41, 36, 9, 1.0, 5.2), 'EDGE_TAG': torn(9, 9, 4, 3.2, 9, .7),
}
CARDS = ['.panel', '.detailCard', '.ordercard', '.couponCard', '.rewardStandalone', '.notificationCard', '.cartItem', '.cartrow', '.transaction',
         '.profilePanel', '.locationPanel', '.walletPayPanel', '.walletDirectPay', '.chatPanel', '.supportThread', '.receipt', '.product', '.profileQuickGrid a', '.profileStats a']

H = 'html[data-secret-theme="on"][data-secret-preset="coraline"]'
s = SRC.read_text()
s = s.replace('@CARDS', ','.join(CARDS))
for k, v in EDGES.items(): s = s.replace('@' + k, v)
s = re.sub(r'@U(?![A-Za-z])', H + '[data-yn-theme][data-yn-theme]:root', s)
s = re.sub(r'@T(?![A-Za-z])', H + '[data-yn-theme]:root', s)
s = re.sub(r'@H(?![A-Za-z])', H, s)
OUT.write_text('/* GENERATED by tools/coraline-art/build_css.py from src/coraline.src.css - edit the .src.css and run the script. */\n' + s)
print('wrote', OUT.relative_to(ROOT), len(s), 'bytes')
