#!/usr/bin/env node
// Schema coverage report: what the CODE uses vs. what the SQL FILES create.
//   node tools/schema-coverage.mjs            -> writes docs/SCHEMA-COVERAGE.md
//   node tools/schema-coverage.mjs --check    -> also exits 1 if anything the app uses is not defined in any SQL file
// Static text scan (no database needed). Drop a real `supabase db dump` into supabase/migrations/ and re-run:
// the "missing" lists should become empty.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const SKIP = new Set(['node_modules', 'dist', '.git', 'android', 'ios', 'build']);
function walk(dir, exts, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, exts, out);
    else if (exts.some((x) => e.name.endsWith(x))) out.push(p);
  }
  return out;
}
const read = (f) => fs.readFileSync(f, 'utf8');
const rel = (f) => path.relative(root, f);

const codeFiles = [...walk(path.join(root, 'src'), ['.ts', '.tsx']), ...walk(path.join(root, 'server'), ['.js', '.mjs']),
  ...(fs.existsSync(path.join(root, 'supabase/functions')) ? walk(path.join(root, 'supabase/functions'), ['.ts']) : [])];
const sqlFiles = walk(root, ['.sql']).filter((f) => !rel(f).startsWith('tests/'));

const used = { tables: new Map(), rpcs: new Map(), buckets: new Map() };
const add = (m, k, f) => { if (!m.has(k)) m.set(k, new Set()); m.get(k).add(rel(f)); };

for (const f of codeFiles) {
  let s = read(f);
  for (const m of s.matchAll(/\.storage\s*\.from\(\s*['"`]([\w-]+)['"`]\s*\)/g)) add(used.buckets, m[1], f);
  s = s.replace(/\.storage\s*\.from\(\s*['"`][\w-]+['"`]\s*\)/g, '');
  for (const m of s.matchAll(/\.from\(\s*['"`]([a-z_][\w]*)['"`]\s*\)/g)) add(used.tables, m[1], f);
  for (const m of s.matchAll(/\.rpc\(\s*['"`]([a-z_][\w]*)['"`]/g)) add(used.rpcs, m[1], f);
  for (const m of s.matchAll(/\bsb\(\s*['"`]rpc\/([a-z_][\w]*)/g)) add(used.rpcs, m[1], f);
  for (const m of s.matchAll(/\bsb\(\s*['"`]([a-z_][\w]*)[?'"`]/g)) if (m[1] !== 'rpc') add(used.tables, m[1], f);
}

const defined = { tables: new Map(), rpcs: new Map(), buckets: new Map() };
for (const f of sqlFiles) {
  const s = read(f);
  for (const m of s.matchAll(/create\s+table\s+(?:if\s+not\s+exists\s+)?(?:public\.)?"?([a-z_][\w]*)"?/gi)) add(defined.tables, m[1].toLowerCase(), f);
  for (const m of s.matchAll(/create\s+(?:or\s+replace\s+)?(?:materialized\s+)?view\s+(?:public\.)?([a-z_][\w]*)/gi)) add(defined.tables, m[1].toLowerCase(), f);
  for (const m of s.matchAll(/create\s+(?:or\s+replace\s+)?function\s+(?:public\.)?([a-z_][\w]*)/gi)) add(defined.rpcs, m[1].toLowerCase(), f);
  for (const m of s.matchAll(/storage\.buckets[\s\S]{0,200}?values\s*\(\s*'([\w-]+)'/gi)) add(defined.buckets, m[1], f);
  for (const m of s.matchAll(/create_bucket\(\s*'([\w-]+)'/gi)) add(defined.buckets, m[1], f);
}

const missing = (kind) => [...used[kind].keys()].filter((k) => !defined[kind].has(k)).sort();
const unused = (kind) => [...defined[kind].keys()].filter((k) => !used[kind].has(k)).sort();
const where = (kind, k) => [...used[kind].get(k)].slice(0, 3).join(', ');

const L = [];
L.push('# Schema coverage (generated)', '',
  `Generated by \`node tools/schema-coverage.mjs\` on ${new Date().toISOString().slice(0, 10)}. Static scan of the code vs. the \`.sql\` files in this repo.`,
  'It does **not** talk to your database. "Missing" means: the app uses it, but no SQL file in this folder creates it, so a fresh Supabase project built only from these files would break.', '',
  `Scanned ${codeFiles.length} code files and ${sqlFiles.length} SQL files.`, '');
for (const [kind, title, hint] of [
  ['tables', 'Tables / views', 'Export these from your live project (see supabase/README.md -> "Create the baseline").'],
  ['rpcs', 'Database functions (RPC)', 'Often defined in the dashboard or an older file. Export them with the baseline.'],
  ['buckets', 'Storage buckets', 'Buckets are usually created by hand in the dashboard. Document them in docs/setup/.']]) {
  const m = missing(kind);
  L.push(`## ${title}`, '', `Used by the app: **${used[kind].size}** · defined in SQL files: **${[...used[kind].keys()].length - m.length}** · **missing: ${m.length}**`, '');
  if (m.length) { L.push(hint, '', '| Name | Used in |', '|---|---|'); for (const k of m) L.push(`| \`${k}\` | ${where(kind, k)} |`); L.push(''); }
  else L.push('Everything the app uses is defined in a SQL file.', '');
  const u = unused(kind);
  if (u.length) L.push(`<details><summary>Defined in SQL but not referenced by the app code (${u.length}) - fine for admin/server-only objects</summary>`, '', u.map((k) => `\`${k}\``).join(', '), '', '</details>', '');
}
fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs/SCHEMA-COVERAGE.md'), L.join('\n'));
const total = missing('tables').length + missing('rpcs').length + missing('buckets').length;
console.log(`tables missing: ${missing('tables').length}, functions missing: ${missing('rpcs').length}, buckets missing: ${missing('buckets').length}`);
console.log('wrote docs/SCHEMA-COVERAGE.md');
if (process.argv.includes('--check') && total) process.exit(1);
