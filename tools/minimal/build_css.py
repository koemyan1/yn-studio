#!/usr/bin/env python3
"""Builds src/minimal.css from src/minimal.src.css.   Run from the project root:   python3 tools/minimal/build_css.py

The only thing it does is expand the scope macro  @S  into the selector that means "customer screens, normal mode":
  html:not([data-secret-theme="on"]):not(.yn-admin-page)  (+ extra weight)
so the minimal look never touches the admin panel or an unlocked Secret Code theme."""
import pathlib
ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC, OUT = ROOT / 'src' / 'minimal.src.css', ROOT / 'src' / 'minimal.css'
# the repeated :not(.yn-admin-page) adds weight on purpose, so these rules beat the older customer rules ('html:not([data-secret-theme="on"]) .shop ...' in home.css etc.)
SCOPE = 'html:not([data-secret-theme="on"]):not(.yn-admin-page):not(.yn-admin-page):not(.yn-admin-page)'
s = SRC.read_text()
out = s.replace('@S', SCOPE)
depth = 0
for ch in out:
    depth += (ch == '{') - (ch == '}')
    assert depth >= 0, 'unbalanced braces'
assert depth == 0, 'unbalanced braces'
OUT.write_text('/* GENERATED by tools/minimal/build_css.py from src/minimal.src.css - edit the .src.css and run the script. */\n' + out)
print('wrote', OUT, len(out), 'bytes')
