#!/usr/bin/env python3
"""
Builds src/chiikawa.css from chiikawa.src.css.

The theme's selectors all start with the same long prefix. To keep the source readable it is written with two short words:
    @R   ->  html[data-secret-theme="on"][data-secret-preset="chiikawa"]
    @RT  ->  html[data-secret-theme="on"][data-secret-preset="chiikawa"][data-yn-theme]:root
(@RT is exactly as specific as the theme engine's own rules, so a part restyled in the Theme Studio still wins.)

Run:  python3 tools/chiikawa-art/build_css.py
You only need this if you want to edit chiikawa.src.css; the app itself just reads the generated src/chiikawa.css.
"""
import pathlib, re
here = pathlib.Path(__file__).resolve().parent
root = here.parent.parent
src = (here / 'chiikawa.src.css').read_text(encoding='utf8')
R = 'html[data-secret-theme="on"][data-secret-preset="chiikawa"]'
RT = R + '[data-yn-theme]:root'
out = re.sub(r'@RT\b', RT, src)
out = re.sub(r'@R\b', R, out)
header = '/* GENERATED by tools/chiikawa-art/build_css.py from chiikawa.src.css – edit the .src.css and run the script, or edit this file directly. */\n'
(root / 'src' / 'chiikawa.css').write_text(header + out, encoding='utf8')
print('wrote src/chiikawa.css', len(out), 'bytes')
